{
  /* Small helper that reads requests, then loads the auth module. 
    Helps prevent issues with random values generated by auth */
}

import "server-only";
import { connection } from "next/server";
import { headers } from "next/headers";
import { auth } from "@/lib/auth";

// Everything after connection() runs only for a real visitor's request,
// never during prerendering, which is when random values aren't allowed.
export async function getSession() {
  await connection();
  return auth.api.getSession({ headers: await headers() });
}